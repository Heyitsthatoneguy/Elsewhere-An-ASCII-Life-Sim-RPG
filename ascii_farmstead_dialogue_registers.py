"""Speech registers: the sentence shapes behind each voice profile.

The profiles in ``ascii_farmstead_dialogue_library`` supply *what* a speaker
knows -- their trade, their worry, the material in their hands. This module
supplies *how* they say it. Before it existed every profile shared one set of
sentence bodies, so a miner, a clerk and a nine-year-old delivered identical
cadences with different nouns swapped in, which is what made a run of
conversation read as generated.

Each register owns its own bodies for all twelve topics. Conventions:

* Base patterns open with ``{vantage}, `` and continue in lower case. The
  renderer drops that opener on most lines and capitalises what follows, so a
  body must read correctly both with and without it.
* Observations carry no opener; the catalog crosses each with ten lenses.
* ``{task}``, ``{place}``, ``{interest}``, ``{people}`` and ``{material}``
  already carry their own articles. Never write "the {task}".
* ``{interest}``, ``{people}`` and ``{material}`` always hold comma lists, so
  they take plural verbs.
"""

